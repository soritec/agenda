/** Frase del giorno ("2026-10-11"); `scarto` per vederne un'altra. Sempre la stessa per lo stesso giorno. */
export function fraseDelGiorno(giorno: string, scarto = 0): string {
  let h = 0
  for (const c of giorno) h = (h * 31 + c.charCodeAt(0)) >>> 0
  return FRASI[(h + scarto) % FRASI.length]!
}
